// Command psloader embeds the vendored PowerSploit reflective PE loader into
// Go source, so that building shellcode2pwsh5 no longer needs a .ps1 file
// next to the code.
//
// The loader is stored gzip-compressed and base64-encoded by default, or as a
// plain Go raw string with -raw. Both forms decode to the original bytes, so
// generated scripts stay bit-for-bit identical to the ones produced from the
// .ps1 file.
//
// Usage:
//
//	go run ./tools/psloader -in Invoke-ReflectivePEInjection.ps1 \
//	    -license PowerSploit-LICENSE -out psloader.go
//
//	go run ./tools/psloader -in Invoke-ReflectivePEInjection.ps1 -raw
//
//	go run ./tools/psloader -extract Invoke-ReflectivePEInjection.ps1
//
// -extract restores the plaintext loader from an existing psloader.go, so the
// compressed form can stay the single source of truth in the tree.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"
)

// glue joins backtick-free raw string segments into one literal that contains
// backticks: `a` + "`" + `b`
const glue = "\x60 + \"\x60\" + \x60"

const blobWidth = 100

func main() {
	in := flag.String("in", "", "PowerShell loader to embed (.ps1)")
	licensePath := flag.String("license", "", "license text to embed (optional)")
	out := flag.String("out", "psloader.go", "generated Go file")
	pkg := flag.String("pkg", "main", "package name of the generated file")
	rawMode := flag.Bool("raw", false, "emit the loader as a Go raw string instead of gzip+base64")
	extract := flag.String("extract", "", "restore the plaintext loader from -go to this path")
	goFile := flag.String("go", "psloader.go", "generated file to read for -extract")
	flag.Parse()

	if *extract != "" {
		n, err := runExtract(*goFile, *extract)
		if err != nil {
			fail(err)
		}
		fmt.Printf("psloader: restored %s (%d bytes) from %s\n", *extract, n, *goFile)
		return
	}
	if *in == "" {
		fail(fmt.Errorf("missing -in <loader.ps1>"))
	}

	loader, err := readASCII(*in, "loader")
	if err != nil {
		fail(err)
	}
	license := ""
	if *licensePath != "" {
		license, err = readASCII(*licensePath, "license")
		if err != nil {
			fail(err)
		}
	}

	var src string
	if *rawMode {
		src, err = rawSource(*pkg, loader, license)
	} else {
		src, err = packedSource(*pkg, loader, license)
	}
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fail(err)
	}

	sum := sha256.Sum256([]byte(loader))
	fmt.Printf("psloader: wrote %s (%d bytes) from %d bytes of loader, sha256 %s\n",
		*out, len(src), len(loader), hex.EncodeToString(sum[:]))
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "psloader: error: %v\n", err)
	os.Exit(1)
}

// readASCII reads a text asset and refuses anything that cannot be embedded
// verbatim. Bytes and line endings are preserved as-is.
func readASCII(path, what string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("cannot read %s: %w", what, err)
	}
	if len(data) == 0 {
		return "", fmt.Errorf("%s file is empty: %s", what, path)
	}
	for i, b := range data {
		if b > 0x7F {
			return "", fmt.Errorf("%s contains a non-ASCII byte at offset %d", what, i)
		}
	}
	return string(data), nil
}

// rawLiteral renders s as a Go raw string literal. Backticks are spliced in
// with glue so that the literal stays readable across lines.
func rawLiteral(s string) (string, error) {
	if strings.IndexByte(s, 0) >= 0 {
		return "", fmt.Errorf("asset contains a NUL byte")
	}
	segments := strings.Split(s, "`")
	for i := range segments {
		segments[i] = "`" + segments[i] + "`"
	}
	return strings.Join(segments, glue), nil
}

func header(pkg string) string {
	return fmt.Sprintf(`// Code generated by tools/psloader; DO NOT EDIT.
//
// PowerSploit - Invoke-ReflectivePEInjection (BSD 3-Clause, see the license
// notice below). The loader lives here so that building shellcode2pwsh5 needs
// no external .ps1 asset.
//
// Regenerate:
//   go run ./tools/psloader -in <loader.ps1> -license <license.txt>
// Restore the plaintext loader:
//   go run ./tools/psloader -extract <loader.ps1>

package %s
`, pkg)
}

func licenseBlock(license string) (string, error) {
	if license == "" {
		return "", nil
	}
	lit, err := rawLiteral(license)
	if err != nil {
		return "", err
	}
	return `// reflectiveLoaderLicense is the PowerSploit BSD 3-Clause notice, prepended
// to every generated script that carries the reflective loader.
const reflectiveLoaderLicense = ` + lit + "\n\n", nil
}

func packedSource(pkg, loader, license string) (string, error) {
	var packed bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&packed, gzip.BestCompression)
	if _, err := zw.Write([]byte(loader)); err != nil {
		return "", err
	}
	if err := zw.Close(); err != nil {
		return "", err
	}
	sum := sha256.Sum256([]byte(loader))
	blob := base64.StdEncoding.EncodeToString(packed.Bytes())

	var b strings.Builder
	b.WriteString(header(pkg))
	b.WriteString(`import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"io"
	"strings"
)

`)
	lb, err := licenseBlock(license)
	if err != nil {
		return "", err
	}
	b.WriteString(lb)
	fmt.Fprintf(&b, `// Shape of the plaintext loader, checked right after decoding.
const (
	reflectiveLoaderSize   = %d
	reflectiveLoaderSHA256 = %q
)

// reflectiveLoaderBlob is the loader, gzip-compressed and base64-encoded.
const reflectiveLoaderBlob = `+"`"+`
`, len(loader), hex.EncodeToString(sum[:]))
	for i := 0; i < len(blob); i += blobWidth {
		end := i + blobWidth
		if end > len(blob) {
			end = len(blob)
		}
		b.WriteString(blob[i:end])
		b.WriteByte('\n')
	}
	b.WriteString("`\n\n")
	b.WriteString(`// reflectiveLoader is the PowerSploit loader exactly as vendored.
var reflectiveLoader = decodeReflectiveLoader()

func decodeReflectiveLoader() string {
	packed, err := base64.StdEncoding.DecodeString(
		strings.NewReplacer("\n", "", "\r", "", " ", "", "\t", "").Replace(reflectiveLoaderBlob))
	if err != nil {
		panic("shellcode2pwsh5: embedded reflective loader is not valid base64: " + err.Error())
	}
	zr, err := gzip.NewReader(bytes.NewReader(packed))
	if err != nil {
		panic("shellcode2pwsh5: embedded reflective loader is not a valid gzip stream: " + err.Error())
	}
	text, err := io.ReadAll(zr)
	if err != nil {
		panic("shellcode2pwsh5: embedded reflective loader cannot be decompressed: " + err.Error())
	}
	sum := sha256.Sum256(text)
	if len(text) != reflectiveLoaderSize || hex.EncodeToString(sum[:]) != reflectiveLoaderSHA256 {
		panic("shellcode2pwsh5: embedded reflective loader is corrupt")
	}
	return string(text)
}
`)
	return b.String(), nil
}

func rawSource(pkg, loader, license string) (string, error) {
	lit, err := rawLiteral(loader)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(header(pkg))
	lb, err := licenseBlock(license)
	if err != nil {
		return "", err
	}
	b.WriteString(lb)
	fmt.Fprintf(&b, "// reflectiveLoader is the PowerSploit loader exactly as vendored.\nconst reflectiveLoader = %s\n", lit)
	return b.String(), nil
}

// runExtract reads the packed blob back out of a generated file and writes the
// plaintext loader. Raw-mode files are rejected: they have no single blob.
func runExtract(goFile, out string) (int, error) {
	src, err := os.ReadFile(goFile)
	if err != nil {
		return 0, fmt.Errorf("cannot read %s: %w", goFile, err)
	}
	const head = "const reflectiveLoaderBlob = `"
	text := string(src)
	start := strings.Index(text, head)
	if start < 0 {
		return 0, fmt.Errorf("%s has no packed loader (was it generated with -raw?)", goFile)
	}
	start += len(head)
	end := strings.IndexByte(text[start:], '`')
	if end < 0 {
		return 0, fmt.Errorf("%s: unterminated loader blob", goFile)
	}
	blob := text[start : start+end]

	packed, err := base64.StdEncoding.DecodeString(
		strings.NewReplacer("\n", "", "\r", "", " ", "", "\t", "").Replace(blob))
	if err != nil {
		return 0, fmt.Errorf("blob is not valid base64: %w", err)
	}
	zr, err := gzip.NewReader(bytes.NewReader(packed))
	if err != nil {
		return 0, fmt.Errorf("blob is not a valid gzip stream: %w", err)
	}
	plain, err := io.ReadAll(zr)
	if err != nil {
		return 0, fmt.Errorf("cannot decompress blob: %w", err)
	}
	if err := os.WriteFile(out, plain, 0o644); err != nil {
		return 0, err
	}
	return len(plain), nil
}
